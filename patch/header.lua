-- npc_hof_cooking.lua
--
--  NPC Friends × Heap of Foods 요리 연동 패치
--  NPC Friends x Heap of Foods cooking patch
--
--  이 파일은 NPC Friends 모드에 추가되는 파일입니다. 원래 모드에는 없습니다.
--  건드리는 기존 파일은 npc_cooking_planner.lua 하나뿐이고, 그것도 맨 끝에
--  한 줄만 덧붙입니다.
--
--  ── 무엇을 고치나 ─────────────────────────────────────────────────────────
--
--  NPC Friends 는 "왈리가 만들 수 있는 요리" 목록을
--  scripts/npc/npc_cooking_recipes.lua 안에 손으로 적어 두었습니다.
--  거기에는 바닐라 요리와 일부 모드 요리만 있어서, Heap of Foods 가 추가한
--  200종이 넘는 요리는 창고에 재료가 아무리 많아도 후보에 오르지 않습니다.
--  게다가 미트볼이 창고에 없으면 무조건 미트볼부터 만들도록 되어 있어서
--  같은 요리만 반복해서 나옵니다.
--
--  이 패치는 요리 목록을 다시 적는 대신, 왈리가 쓸 수 있는 재료로 조합을
--  만들어 보고 게임 자체의 요리 판정 함수(cooking.CalculateRecipe)에
--  "이 조합은 무슨 요리가 되나?" 하고 직접 물어봅니다. 그래서 정상적인
--  방법으로 등록된 음식 모드라면 무엇이든 자동으로 인식됩니다.
--  거기에 최근에 만든 요리와 이미 창고에 쌓인 요리에 감점을 주어
--  메뉴가 계속 바뀌도록 합니다.
--
--  ── 설정 ──────────────────────────────────────────────────────────────────
--  아래 USER_SETTINGS 값만 고치면 됩니다. 고친 뒤 DST 를 껐다 켜세요.

local USER_SETTINGS =
{
	-- 패치 사용 여부. false 로 두면 NPC Friends 원래 로직을 그대로 씁니다.
	enabled = true,

	-- 요리 다양성. "off" / "low" / "medium" / "high"
	--   off    = 가장 좋은 요리만 계속 만듭니다 (원래 동작에 가까움)
	--   high   = 최근에 만든 요리를 강하게 피하고 새 요리를 시도합니다
	variety = "medium",

	-- 레시피 탐색량. "low" / "medium" / "high"
	--   높을수록 더 많은 종류를 찾아내지만 서버가 조금 더 일합니다.
	--   재료 30종 · 음식 모드 3개 기준, 모드 요리 37가지 중
	--     low    26가지를 찾음   최초 1회 5ms
	--     medium 30가지를 찾음   최초 1회 10ms
	--     high   30가지를 찾음   최초 1회 16ms
	budget = "medium",

	-- 같은 요리를 창고에 몇 개까지 쌓을지. 0 이면 NPC Friends 설정을 따릅니다.
	same_dish_max = 0,

	-- 체력이나 정신력이 깎이는 요리도 만들게 할지.
	--   커피 종류는 원래 정신력을 깎는 것이 컨셉이라 (정신력 -5),
	--   false 로 두면 DST Coffee and More 의 요리가 하나도 안 나옵니다.
	--   할로윈 모드의 멜론·생선스틱(정신력 -10)도 마찬가지입니다.
	allow_negative = true,

	-- 한 가지를 두 번 만들기 전에, 아직 한 번도 안 만든 요리를 먼저 만들지.
	--   요리 값어치 차이가 너무 커서(제일 좋은 것 330, 에스프레소 3),
	--   이게 없으면 값싼 모드 요리는 영원히 안 나옵니다.
	--   한 바퀴 돌고 나면 다시 값어치 순으로 돌아갑니다.
	--   variety = "off" 면 이 설정과 상관없이 항상 제일 좋은 요리만 만듭니다.
	taste_everything = true,

	-- 왈리가 요리를 못 하겠다고 할 때, 왜 못 하는지 서버 로그에 설명합니다.
	-- (상자를 못 찾았는지 / 재료가 아닌지 / 냄비가 없는지 / 가방이 꽉 찼는지)
	explain = true,

	-- 어떤 요리를 왜 골랐는지까지 전부 출력합니다. 자세한 문제 확인용.
	debug = false,

	-- 절대 재료로 쓰지 않을 아이템. 예: protect = { butter = true, mandrake = true }
	protect = {},

	-- 요리 도구를 돌아가며 쓰게 할지.
	--   NPC Friends 는 근처에서 "stewer" 표가 붙은 것을 전부 냄비로 봅니다.
	--   그런데 왈리의 휴대용 양념기도 거기 걸립니다. 양념기는 칸이 2개뿐이고
	--   요리된 음식과 향신료만 받는데, 왈리 NPC 는 언제나 4칸짜리 요리를
	--   들고 갑니다. 그래서 양념기를 고르면 아무것도 못 넣고 요리가 실패합니다.
	--   true 로 두면 4칸이 안 되는 도구는 건너뛰고, 쓸 수 있는 냄비는
	--   돌아가며 씁니다. (다 만든 음식을 거두는 것은 그대로입니다)
	spread_cookware = true,

	-- 왈리의 휴대용 양념기를 쓰게 할지.
	--   요리된 음식 + 향신료를 양념기에 넣어 양념 요리를 만듭니다.
	--   (마늘가루=피해감소, 고춧가루=공격력, 설탕=작업속도, 소금=맛)
	--
	--   NPC Friends 의 행동 파일은 "재료 4개를 안 들고 있으면 포기" 하게
	--   되어 있는데 양념기는 칸이 2개뿐입니다. 그래서 그 파일이 쓰는
	--   NPCCookingBehavior 의 함수 두 개를 감싸서 통과시킵니다.
	--   맞물리지 않으면 알아서 포기하고 지금까지와 똑같이 동작합니다.
	--
	--   요리와 번갈아 합니다. 양념기가 계속 거부하면 몇 번 뒤에 포기합니다.
	use_spicer = true,

	-- 건조대에 고기와 버섯을 널게 할지.
	--   말린 고기 / 말린 버섯은 안 상하고 오래 갑니다.
	--   Heap of Foods 를 쓰시면 말릴 수 있는 것이 더 많아집니다.
	--
	--   건조대는 냄비가 아닙니다. 칸도 없고(한 개씩 올립니다), 부품이 쓰는
	--   말도 다르고(CanDry/StartDrying), NPC Friends 가 찾는 표도 안 달려
	--   있습니다. 그래서 건조대를 "냄비처럼 보이는 대역"으로 감싸 넘깁니다.
	--   세상에 있는 진짜 건조대에는 아무것도 안 붙입니다. 세이브도 안 건드립니다.
	--
	--   양념기와 건조대는 각각 따로 셉니다. 한쪽이 말을 안 들어도
	--   다른 쪽은 계속 돌아갑니다.
	use_dryer = true,
}

